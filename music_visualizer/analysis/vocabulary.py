def load_vocab(path: str | None) -> List[str]:
    """Load a vocabulary JSON (flat array of strings), or the built-in default.

    Raises ``ValueError`` if the file exists but isn't a non-empty list of
    strings, so a malformed override fails loudly instead of silently falling
    back.
    """
    if not path:
        return list(DEFAULT_VOCAB)
    data = json.loads(Path(path).read_text(encoding="utf-8"))
    if not isinstance(data, list) or not data or not all(
        isinstance(x, str) and x.strip() for x in data
    ):
        raise ValueError(
            f"CLAP vocab file {path!r} must be a non-empty JSON array of strings."
        )
    return [x.strip() for x in data]
